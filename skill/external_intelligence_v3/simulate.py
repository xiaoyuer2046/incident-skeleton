#!/usr/bin/env python3
"""Generate deterministic v3 demo data from the real engine (SIMULATED, DRY-RUN)."""
from __future__ import annotations

import argparse
import json
import os
import tempfile
from typing import Any, Dict

try:
    from .engine import GlobalIntelligenceEngine, EXTERNAL
except ImportError:  # direct run
    from engine import GlobalIntelligenceEngine, EXTERNAL

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DEFAULT_SIGNALS = os.path.join(HERE, "signals.json")
DEFAULT_OUTPUT = os.path.join(ROOT, "demo", "data", "global-intelligence-v3.js")
HOLDING = ("vendor_incident_confirmed", "global_outage_likely")


def build_demo(signals_path: str = DEFAULT_SIGNALS) -> Dict[str, Any]:
    with open(signals_path, encoding="utf-8") as handle:
        cycles_in = json.load(handle)["cycles"]
    engine = GlobalIntelligenceEngine()  # in-memory: demo never touches saved state
    cycles, peak_active, peak_held, peak_conf = [], 0, 0, 0.0
    ext_sources, internal_count = set(), 0
    for item in cycles_in:
        cyc = engine.run_cycle(item["signals"], item["ts"])
        cyc["ts"] = item["ts"][11:16]
        for s in cyc["signals"]:
            if s["source"] in EXTERNAL:
                ext_sources.add((s["provider"], s["source"]))
            else:
                internal_count += 1
        active = [d for d in cyc["decisions"] if d["decision"] in HOLDING]
        peak_active = max(peak_active, len(active))
        peak_held = max(peak_held, sum(len(d["recommendation"]["hold"]) for d in active))
        peak_conf = max([peak_conf] + [d["confidence"] for d in cyc["decisions"]])
        cyc["ts_full"] = item["ts"]
        cycles.append(cyc)
    providers = {c["provider"] for c in engine.config["connectors"]}
    return {
        "version": "3.0",
        "generated_at": cycles_in[-1]["ts"],
        "dry_run": True,
        "simulated": True,
        "label": {"en": "SIMULATED DATA - DRY-RUN", "zh": "模拟数据 - 演练模式"},
        "summary": {
            "monitored_providers": len(providers),
            "external_sources": len(ext_sources),
            "internal_signals": internal_count,
            "active_global_incidents": peak_active,
            "held_local_actions": peak_held,
            "confidence": peak_conf,
            "note": "incident, held-action and confidence values are peaks over the story",
        },
        "connectors": [
            {"id": c["id"], "provider": c["provider"], "label": c["label"], "status": c["status"],
             "authenticated": c["authenticated"], "required_scope": c["required_scope"]}
            for c in engine.config["connectors"]
        ],
        "cycles": cycles,
    }


def validate_demo(demo: Dict[str, Any]) -> None:
    need = {"version", "generated_at", "summary", "cycles"}
    assert need <= set(demo), "missing top-level keys"
    assert set(demo["summary"]) >= {"monitored_providers", "external_sources", "internal_signals",
                                    "active_global_incidents", "held_local_actions", "confidence"}
    for cyc in demo["cycles"]:
        assert {"ts", "signals", "correlations", "decisions", "notices", "patterns", "versions"} <= set(cyc)
        for n in cyc["notices"]:
            assert n["dry_run"] and n["en"]["body"] and n["zh"]["body"]
    flat = {d["key"]: [] for c in demo["cycles"] for d in c["decisions"]}
    for c in demo["cycles"]:
        for d in c["decisions"]:
            flat[d["key"]].append(d["decision"])
    assert "vendor_incident_confirmed" in flat["microsoft|teams"] and flat["microsoft|teams"][-1] == "resolved"
    assert "local_issue_likely" in flat["cisco|meraki"]


def write_demo(path: str = DEFAULT_OUTPUT, signals_path: str = DEFAULT_SIGNALS) -> Dict[str, Any]:
    demo = build_demo(signals_path)
    validate_demo(demo)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    body = json.dumps(demo, ensure_ascii=False, indent=1)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("// Generated by skill/external_intelligence_v3/simulate.py. SIMULATED, DRY-RUN.\n")
        handle.write("window.GLOBAL_INTELLIGENCE_V3 = %s;\n" % body)
    return demo


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    demo = write_demo(args.output)
    print("wrote %s (%d cycles)" % (args.output, len(demo["cycles"])))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
