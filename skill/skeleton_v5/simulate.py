#!/usr/bin/env python3
"""Write demo/data/skeleton-v5.js (window.SKELETON_V5) from one run of skeleton_v5/run.py. SIMULATED, DRY-RUN.

    python skill/skeleton_v5/simulate.py [--output demo/data/skeleton-v5.js]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Dict

if __package__ in (None, ""):  # direct run
    sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
    __package__ = "skeleton_v5"

from skeleton_v5 import ROOT, news as N, permissions as P, run  # noqa: E402
from skeleton_v4 import skeleton  # noqa: E402

DEFAULT_OUTPUT = os.path.join(ROOT, "demo", "data", "skeleton-v5.js")
GENERATED_AT = "2026-11-21T09:30:00Z"


def _lines(path: str) -> int:
    with open(path, encoding="utf-8") as handle:
        return sum(1 for _ in handle)


def payload() -> Dict[str, Any]:
    out = run.build()
    c0, c1 = out["news"]
    items = []
    for r in out["rows"]:
        rec = r["record"]
        items.append({"phase": r["phase"], "app": rec["app"], "label": rec["label"], "outcome": rec["outcome"], "parent": rec["parent"],
                      "held": rec["held_actions"], "notes": [{"en": n["en"], "zh": n["zh"]} for n in rec["learning_used"]],
                      "steps": [{k: s[k] for k in ("name", "status", "slot", "en", "zh")} for s in rec["steps"]]})
    props = []
    for p in out["book"].proposals.values():
        props.append({"id": p["id"], "label": p["label"], "from": p["from"], "to": p["to"], "state": p["state"], "state_label": P.STATES[p["state"]],
                      "approver": p["approver"], "expires_at": p["expires_at"], "evidence": p["evidence"],
                      "why": P.WHY[p["reason"]] if p["reason"] else None, "sources": p["sources"]})
    refused = [{"by": d["by"], "action": d["action"], "why": d["text"]} for d in out["decisions"] if not d["ok"]]
    return {
        "generated_at": GENERATED_AT, "dry_run": True, "simulated": True, "runtime_file": "skill/skeleton_v4/skeleton.py",
        "runtime_lines": _lines(skeleton.__file__),
        "systems": [{k: h[k] for k in ("id", "label", "kind", "status", "text", "scopes", "secret_env")} for h in out["health"]],
        "synced": [{k: t[k] for k in ("id", "system", "site", "opened_at", "text", "text_zh", "service")} for t in out["synced"]],
        "groups": out["groups"],
        "news": {"at": c0["checked_at"], "level": c0["level"], "label": c0["label"], "count": c0["count"], "need": c0["need"],
                 "sources": c0["sources"], "dropped": [dict(d, why_label=N.DROP[d["why"]]) for d in c0["dropped"]],
                 "later": {"at": c1["checked_at"], "level": c1["level"], "label": c1["label"]}},
        "notices": [{"kind": n["kind"], "to": n["to"], "en": n["en"], "zh": n["zh"]} for n in out["notices"]],
        "items": items, "proposals": props, "refused": refused,
        "metrics": {k: v for k, v in out["metrics"].items() if k != "dry_run"},
        "metric_labels": run.METRIC,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    data = payload()
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("/* Generated by skill/skeleton_v5/simulate.py. SIMULATED dry-run data; nothing was sent or executed. */\n")
        handle.write("window.SKELETON_V5 = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    print("wrote %s (%d items, %d systems)" % (os.path.relpath(args.output, ROOT), len(data["items"]), len(data["systems"])))


if __name__ == "__main__":
    main()
